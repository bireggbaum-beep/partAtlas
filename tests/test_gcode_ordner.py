"""G-Code aus dem Ordner als regulärer Weg neben dem Hochladen: das Quellmodell steht im Inhalt, der Slicer schreibt Sonderzeichen um."""
import os
import tempfile
import time

import muster
from muster import check
from fastapi.testclient import TestClient
from partatlas.main import erstelle_app


def warten(z):
    z["scanner"].warten(120)
    z["scanner"].worker.warten(120)


def gcode(objekte, zeit="1h 0m 0s", gewicht=12.5, stil="orca", extra=""):
    """Nachgebauter Kopf wie Orca/Anycubic (Klipper-Objektliste) oder Prusa (Kommentar je Objekt)."""
    kopf = f"; generated by OrcaSlicer 2.1.1\n; model printing time: {zeit}\n; total filament weight [g] : {gewicht}\n{extra}"
    if stil == "orca":
        kopf += "".join(f"EXCLUDE_OBJECT_DEFINE NAME={o}_id_{i}_copy_0 CENTER=10,10\n" for i, o in enumerate(objekte))
        kopf += "".join(f'; printing object "{o}"\n' for o in objekte)
    elif stil == "prusa":
        kopf += "".join(f"; printing object {o} id:{i} copy 0\n" for i, o in enumerate(objekte))
    return (kopf + "G1 X1 Y1\n" * 50).encode()


def modell(c, name):
    return next((m for m in c.get("/api/modelle").json() if m["name"] == name), None)


if __name__ == "__main__":
    tmp = tempfile.mkdtemp()
    sammlung = os.path.join(tmp, "3D-Druck")
    zwei = os.path.join(sammlung, "zweite")
    os.makedirs(zwei)

    def schreibe(pfad, daten):
        with open(pfad, "wb") as f:
            f.write(daten)

    for n, x in [("Halter_Netzteil", 10), ("Testscheibe_45mm", 11), ("Prusateil", 12), ("Gehaeuse_Lang_Name", 13), ("Doppelt", 14)]:
        muster.stl_binaer(os.path.join(sammlung, n + ".stl"), x, 20, 30)
    muster.stl_binaer(os.path.join(zwei, "Doppelt.stl"), 99, 20, 30)           # zweites Modell mit demselben Namen: unklar
    schreibe(os.path.join(sammlung, "1009-Halter.gcode"), gcode(["Halter_Netzteil.stl"]))
    schreibe(os.path.join(sammlung, "1009-1926-Testscheibe_45mm-Cut002_plate01_PLA_0.2_3m17s.gcode"), gcode(["Testscheibe_4_5mm.stl"], zeit="3m 17s"))
    schreibe(os.path.join(sammlung, "prusa.gcode"), gcode(["Prusateil.stl"], stil="prusa"))
    schreibe(os.path.join(sammlung, "zwei_objekte.gcode"), gcode(["Prusateil.stl", "Halter_Netzteil.stl"], gewicht=30))
    schreibe(os.path.join(sammlung, "unklar.gcode"), gcode(["Doppelt.stl"]))
    schreibe(os.path.join(sammlung, "fremd.gcode"), gcode(["Gibt_es_nicht.stl"]))
    schreibe(os.path.join(sammlung, "ohne_namen_Gehaeuse_Lang_Name_PLA.gcode"), b"; generated by Cura\n;TIME:600\nG1 X1\n" * 5)

    with TestClient(erstelle_app(os.path.join(tmp, "bestand"), prozesse=1)) as c:
        z = c.app.state.zustand
        c.post("/api/wurzeln", json={"pfad": sammlung})
        warten(z)
        st = c.get("/api/stand").json()["scan"]
        h, t, p, g, d = (modell(c, n) for n in ("Halter_Netzteil", "Testscheibe_45mm", "Prusateil", "Gehaeuse_Lang_Name", "Doppelt"))
        druecke = lambda m: c.get(f"/api/modelle/{m['id']}").json()["drucke"]

        check("Orca/Anycubic: das Quellmodell steht im Inhalt, der G-Code hängt am Modell (Zeichen G-Code auf der Kachel)", h["gcode"] == "druck")
        check("Umgeschriebene Sonderzeichen (Testscheibe_4_5mm im Inhalt, 45mm im Namen) finden das Modell", t["gcode"] == "druck")
        check("PrusaSlicer: Kommentar je Objekt", p["gcode"] == "druck")
        check("Dateiname als Rückfall, wenn der Inhalt kein Modell nennt (ein längster Treffer)", g["gcode"] == "druck")
        check("Zwei Modelle mit demselben Namen: unklar, nichts zugeordnet", d["gcode"] is None)
        check("Der Druck ist „offen“: das Modell gilt nicht als gedruckt", h["drucke_n"] == 0 and not c.get(f"/api/modelle/{h['id']}").json().get("gedruckt"))
        dh = druecke(h)
        check("… trägt Dauer und Gewicht aus dem Kopf und das Datum der Datei",
              len(dh) == 2 and {x["ergebnis"] for x in dh} == {"offen"} and any(x["gewicht_g"] == 12.5 and x["dauer_s"] == 3600 for x in dh)
              and all(x["datum"] == time.strftime("%Y-%m-%d") for x in dh))
        check("Ein G-Code mit zwei Objekten hängt an beiden Modellen", len(druecke(p)) == 2 and len(dh) == 2)
        check("Die Bilanz zählt: 5 neu, 1 unklar, 1 ohne Modell",
              (st["gcode_neu"], st["gcode_unklar"], st["gcode_ohne_modell"]) == (5, 1, 1))
        check("Die Datei bleibt im Ordner liegen", os.path.exists(os.path.join(sammlung, "1009-Halter.gcode")))

        # -- zweites Einlesen: nichts doppelt
        c.post("/api/scan")
        warten(z)
        check("Ein zweites Einlesen legt keinen Druck doppelt an", len(druecke(modell(c, "Halter_Netzteil"))) == 2)

        # -- derselbe Inhalt, hochgeladen: kein zweiter Druck aus dem Ordner
        schreibe(os.path.join(sammlung, "kopie.gcode"), gcode(["Halter_Netzteil.stl"]))
        c.post("/api/scan")
        warten(z)
        check("Derselbe Inhalt unter anderem Namen: kein zweiter Druck", len(druecke(modell(c, "Halter_Netzteil"))) == 2)

        # -- ein Modell kommt später dazu: der frühere „ohne Modell“ wird zugeordnet
        muster.stl_binaer(os.path.join(sammlung, "Gibt_es_nicht.stl"), 7, 20, 30)
        c.post("/api/scan")
        warten(z)
        check("Kommt das Modell später dazu, wird der liegengebliebene G-Code zugeordnet", modell(c, "Gibt_es_nicht")["gcode"] == "druck")

        # -- Modell im Papierkorb: nicht als Ziel
        c.post(f"/api/modelle/{p['id']}/loeschen", json={})
        schreibe(os.path.join(sammlung, "nachzuegler.gcode"), gcode(["Prusateil.stl"], gewicht=1))
        c.post("/api/scan")
        warten(z)
        check("Ein Modell im Papierkorb bekommt keinen G-Code mehr", c.get("/api/stand").json()["scan"]["gcode_ohne_modell"] >= 1)

        # -- Bereinigen: G-Code ohne Modell
        offen = c.get("/api/gcode_offen").json()
        je = {e["name"]: e for e in offen["eintraege"]}
        check("Bereinigen listet die nicht zugeordneten G-Codes mit Art und genannten Namen",
              je.get("unklar.gcode", {}).get("art") == "unklar" and je["unklar.gcode"]["namen"] == ["Doppelt.stl"]
              and je.get("nachzuegler.gcode", {}).get("art") == "ohne")
        kand = je["unklar.gcode"]["kandidaten"]
        check("… bei „unklar“ mit beiden Modellen gleichen Namens als Kandidaten, je mit Ordner",
              len(kand) == 2 and {k["name"] for k in kand} == {"Doppelt"} and {k["ordner"] for k in kand} == {"3D-Druck", "3D-Druck/zweite"})
        check("Die Seitenleiste zählt sie", c.get("/api/zaehler").json()["gcode"] == len(offen["eintraege"]))
        ziel = next(k for k in kand if k["ordner"].endswith("zweite"))
        r = c.post("/api/gcode_offen/zuordnen", json={"id": je["unklar.gcode"]["id"], "modelle": [ziel["id"]]})
        dd = c.get(f"/api/modelle/{ziel['id']}").json()
        check("Von Hand zuordnen hängt den G-Code an das gewählte Modell (Druck „offen“)",
              r.status_code == 200 and [x["ergebnis"] for x in dd["drucke"]] == ["offen"] and dd["drucke"][0]["datei"]["name"] == "unklar.gcode")
        check("… und er verschwindet aus der Liste", "unklar.gcode" not in {e["name"] for e in c.get("/api/gcode_offen").json()["eintraege"]})
        c.post("/api/scan")
        warten(z)
        check("Ein Einlesen danach lässt ihn in Ruhe (kein zweiter Druck, nicht wieder in der Liste)",
              len(c.get(f"/api/modelle/{ziel['id']}").json()["drucke"]) == 1
              and "unklar.gcode" not in {e["name"] for e in c.get("/api/gcode_offen").json()["eintraege"]})
        nid = je["nachzuegler.gcode"]["id"]
        c.post("/api/gcode_offen/ausblenden", json={"id": nid, "an": True})
        o2 = c.get("/api/gcode_offen").json()
        check("„Nicht zuordnen“ blendet ihn aus und zählt ihn als ausgeblendet",
              nid not in {e["id"] for e in o2["eintraege"]} and o2["ausgeblendet"] == 1
              and [x["id"] for x in c.get("/api/gcode_offen/ausgeblendet").json()] == [nid])
        muster.stl_binaer(os.path.join(sammlung, "Noch_Eins.stl"), 3, 20, 30)          # neues Modell: Unzugeordnete werden neu angesehen …
        c.post("/api/scan")
        warten(z)
        check("… ein Einlesen holt einen ausgeblendeten nicht zurück", nid not in {e["id"] for e in c.get("/api/gcode_offen").json()["eintraege"]})
        c.post("/api/gcode_offen/ausblenden", json={"id": nid, "an": False})
        check("Zurückholen zeigt ihn wieder, mit seiner Art", next((e["art"] for e in c.get("/api/gcode_offen").json()["eintraege"] if e["id"] == nid), None) == "ohne")
        check("Zuordnen an ein Modell, das es nicht gibt: verständliche Meldung",
              c.post("/api/gcode_offen/zuordnen", json={"id": nid, "modelle": ["m_gibtsnicht"]}).status_code == 400)

        # -- Ein Einlesen überschreibt nicht, was der Anwender während des Laufs entschieden hat
        from partatlas.gcode_ordner import GcodeOrdner, GESEHEN
        go = GcodeOrdner(z["katalog"], z["bestand"])
        vorher = dict(z["bestand"].einstellungen()[GESEHEN])
        lauf_sieht = {k: list(v) for k, v in vorher.items()}            # das Ergebnis eines Laufs, der begann, bevor der Anwender zuordnete
        go.ausblenden(nid, True)                                          # … der Anwender entscheidet währenddessen
        go._merken(vorher, lauf_sieht, vollstaendig=True)
        check("Das Ende eines Einlesens überschreibt eine Entscheidung während des Laufs nicht", z["bestand"].einstellungen()[GESEHEN][nid][2] == "ignoriert")
    muster.ende()
