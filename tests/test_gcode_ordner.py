def gcode(objekte, zeit="1h 0m 0s", gewicht=12.5, stil="orca", extra=""):
    """Nachgebauter Kopf wie Orca/Anycubic (Klipper-Objektliste) oder Prusa (Kommentar je Objekt)."""
    kopf = f"; generated by OrcaSlicer 2.1.1\n; model printing time: {zeit}\n; total filament weight [g] : {gewicht}\n{extra}"
    if stil == "orca":
        kopf += "".join(f"EXCLUDE_OBJECT_DEFINE NAME={o}_id_{i}_copy_0 CENTER=10,10\n" for i, o in enumerate(objekte))
        kopf += "".join(f'; printing object "{o}"\n' for o in objekte)
    elif stil == "prusa":
        kopf += "".join(f"; printing object {o} id:{i} copy 0\n" for i, o in enumerate(objekte))
    return (kopf + "G1 X1 Y1\n" * 50).encode()


def gcode_3mf(objekte, zeit_s=646, gewicht=9.87):
    """Nachgebaut nach einer `.gcode.3mf` aus Anycubic Slicer Next (4.11.2026): der G-Code der Platte als Metadata/plate_1.gcode, dazu
    Plattenbild, slice_info.config (Dauer, Gewicht) und die Prüfsumme — kein Modell im 3D-Teil, wie beim Slicer."""
    import io
    import zipfile
    puffer = io.BytesIO()
    g = gcode(objekte, zeit="10m 46s", gewicht=gewicht)
    with zipfile.ZipFile(puffer, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", '<?xml version="1.0"?><Types/>')
        z.writestr("_rels/.rels", '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                   '<Relationship Target="/3D/3dmodel.model" Id="rel-1" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>')
        z.writestr("3D/3dmodel.model", '<model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">'
                   '<metadata name="Application">AnycubicSlicerNext-2.0.0.5</metadata><resources/><build/></model>')
        z.writestr("Metadata/plate_1.png", muster.PNG_1PX)
        z.writestr("Metadata/plate_1.gcode", g)
        z.writestr("Metadata/plate_1.gcode.md5", "0" * 32)
        z.writestr("Metadata/slice_info.config", f'<config><plate><metadata key="index" value="1"/><metadata key="prediction" value="{zeit_s}"/>'
                   f'<metadata key="weight" value="{gewicht}"/><filament id="1" type="PETG" color="#000000" used_m="3.2" used_g="{gewicht}"/></plate></config>')
    return puffer.getvalue()


