"""Das G-Code-Zeichen auf der Kachel und in der Liste, die Suche gcode:ja, ein Klick öffnet den Reiter; der Schriftzug oben heisst „partAtlas“."""
import os
import socket
import subprocess
import sys
import tempfile
import urllib.request

import muster
from muster import check
from test_bereinigen_ui import abfrage, chromium, warte

HIER = os.path.dirname(os.path.abspath(__file__))
GCODE = (b"; generated by OrcaSlicer 2.0\\n; total filament weight [g] : 2\\n; HEADER_BLOCK_END\\n; CONFIG_BLOCK_START\\n; wall_loops = 2\\n"
         b"; CONFIG_BLOCK_END\\nG28\\n")

if __name__ == "__main__":
    muster.zeitgrenze(90)
    from playwright.sync_api import sync_playwright
    tmp = tempfile.mkdtemp()
    samm = os.path.join(tmp, "3D")
    os.makedirs(samm)
    muster.stl_binaer(os.path.join(samm, "Mit.stl"), 10, 20, 30)
    muster.stl_binaer(os.path.join(samm, "Ohne.stl"), 12, 20, 30)
    muster.dreimf(os.path.join(samm, "Geslict.3mf"))
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        port = s.getsockname()[1]
    umgebung = {**os.environ, "PARTATLAS_BESTAND": os.path.join(tmp, "bestand"), "PARTATLAS_PORT": str(port),
                "PYTHONPATH": os.environ.get("PARTATLAS_QUELLE") or os.path.join(HIER, "..")}
    server = subprocess.Popen([sys.executable, "-m", "partatlas"], env=umgebung, cwd=tmp, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        warte(lambda: abfrage(port, "/api/zaehler") is not None)
        abfrage(port, "/api/neuigkeiten/gesehen", {})
        abfrage(port, "/api/wurzeln", {"pfad": samm})
        warte(lambda: len(abfrage(port, "/api/modelle")) == 3)
        ids = {m["name"]: m["id"] for m in abfrage(port, "/api/modelle")}
        did = abfrage(port, "/api/drucke", {"modelle": [ids["Mit"]], "felder": {}})["id"]
        r = urllib.request.Request(f"http://127.0.0.1:{port}/api/drucke/{did}/datei?name=mit.gcode", method="POST", data=GCODE,
                                   headers={"Content-Type": "application/octet-stream"})
        urllib.request.urlopen(r).read()
        with sync_playwright() as p:
            b = p.chromium.launch(executable_path=chromium())
            pg = b.new_page(viewport={"width": 1400, "height": 800})
            pg.goto(f"http://127.0.0.1:{port}/")
            pg.wait_for_selector(".karte")
            pg.wait_for_selector(".badge.gcode")
            pg.screenshot(path="/tmp/claude-0/-home-user/a87771ce-acd8-5417-a6e2-9a56023b0bc8/scratchpad/gcode_karten.png")
            wo = lambda n: pg.locator(".karte", has_text=n).locator(".badge.gcode").count()
            check("Zeichen „G-Code“ bei dem Modell mit angehängtem G-Code und beim geslicten 3MF, nicht beim anderen",
                  wo("Mit") == 1 and wo("Geslict") == 1 and wo("Ohne") == 0)
            ort = lambda n, sel: pg.eval_on_selector(f".karte:has-text('{n}') {sel}", "e => { const r = e.getBoundingClientRect(), k = e.closest('.karte').getBoundingClientRect(); return [Math.round(k.right - r.right), Math.round(k.bottom - r.bottom)]; }")
            check("Feste Plätze: das G-Code-Zeichen sitzt in jeder Kachel am selben Ort, mit und ohne ✓ daneben; das ✓ steht links davon",
                  ort("Mit", ".badge.gcode") == ort("Geslict", ".badge.gcode")
                  and pg.eval_on_selector(".karte:has-text('Mit') .badge.gedruckt", "e => e.getBoundingClientRect().right") <= pg.eval_on_selector(".karte:has-text('Mit') .badge.gcode", "e => e.getBoundingClientRect().left"))
            check("Der Hinweis nennt, wo der G-Code steckt",
                  "bei den Drucken" in pg.get_attribute(".karte:has-text('Mit') .badge.gcode", "title")
                  and "geslict" in pg.get_attribute(".karte:has-text('Geslict') .badge.gcode", "title"))
            pg.click(".karte:has-text('Mit') .badge.gcode")
            pg.wait_for_selector("#inspektor .i-reiter")
            pg.wait_for_function("document.querySelector('#inspektor').dataset.reiter === 'drucke'")
            check("Ein Klick auf das Zeichen wählt das Modell und öffnet den Reiter Drucke mit dem G-Code",
                  "mit.gcode" in pg.inner_text("#inspektor").lower())
            pg.click(".karte:has-text('Geslict') .badge.gcode")
            pg.wait_for_function("document.querySelector('#inspektor').dataset.reiter === 'slicer'")
            check("Beim geslicten 3MF öffnet es den Reiter Slicer", pg.evaluate("document.querySelector('#inspektor').dataset.reiter") == "slicer")
            pg.fill("#suche", "gcode:ja")
            pg.wait_for_function("document.querySelectorAll('.karte').length === 2")
            check("Die Suche gcode:ja zeigt genau die beiden, beide mit dem Zeichen", pg.locator(".karte").count() == 2 and pg.locator(".karte .badge.gcode").count() == 2
                  and pg.locator(".karte", has_text="Ohne").count() == 0)
            pg.fill("#suche", "")
            check("Der Schriftzug oben heisst „PartAtlas“, nicht in Grossbuchstaben", pg.inner_text(".logo").startswith("PartAtlas") and "PARTATLAS" not in pg.inner_text(".logo"))
            b.close()
    finally:
        server.terminate()
        server.wait(10)
    muster.ende()
