"""Bereinigen › G-Code ohne Modell: Zahl in der Seitenleiste, je G-Code der Grund und die passenden Modelle, Klick ordnet zu, „Modell wählen …“ sucht."""
import os
import socket
import subprocess
import sys
import tempfile

import muster
from muster import check
from test_bereinigen_ui import abfrage, chromium, warte

HIER = os.path.dirname(os.path.abspath(__file__))
SCRATCH = os.environ.get("PARTATLAS_BILDER")       # wohin ein Bildschirmfoto soll (nur zum Ansehen)


def gcode(obj):
    return (f"; generated by OrcaSlicer 2.1.1\n; model printing time: 1h 0m 0s\nEXCLUDE_OBJECT_DEFINE NAME={obj}_id_0_copy_0\n" + "G1 X1\n" * 20).encode()


if __name__ == "__main__":
    muster.zeitgrenze(120)
    from playwright.sync_api import sync_playwright
    tmp = tempfile.mkdtemp()
    samm = os.path.join(tmp, "3D")
    os.makedirs(os.path.join(samm, "alt"))
    muster.stl_binaer(os.path.join(samm, "Doppelt.stl"), 10, 20, 30)
    muster.stl_binaer(os.path.join(samm, "alt", "Doppelt.stl"), 11, 20, 30)
    muster.stl_binaer(os.path.join(samm, "Halter_Umbenannt.stl"), 12, 20, 30)
    open(os.path.join(samm, "unklar.gcode"), "wb").write(gcode("Doppelt.stl"))
    open(os.path.join(samm, "0930-1200-Halter_plate01.gcode"), "wb").write(gcode("Halter_Alt.stl"))
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        port = s.getsockname()[1]
    umgebung = {**os.environ, "PARTATLAS_BESTAND": os.path.join(tmp, "bestand"), "PARTATLAS_PORT": str(port),
                "PYTHONPATH": os.environ.get("PARTATLAS_QUELLE") or os.path.join(HIER, "..")}
    server = subprocess.Popen([sys.executable, "-m", "partatlas"], env=umgebung, cwd=tmp, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        warte(lambda: abfrage(port, "/api/zaehler") is not None)
        abfrage(port, "/api/neuigkeiten/gesehen", {})
        abfrage(port, "/api/wurzeln", {"pfad": samm})
        warte(lambda: (abfrage(port, "/api/zaehler") or {}).get("gcode") == 2)
        with sync_playwright() as p:
            b = p.chromium.launch(executable_path=chromium())
            pg = b.new_page(viewport={"width": 1400, "height": 800})
            pg.goto(f"http://127.0.0.1:{port}/")
            pg.click(".rail-btn[data-rail='bereinigen']")
            pg.wait_for_function("document.querySelector('#z-gcode')?.textContent === '2'")
            check("Seitenleiste: „G-Code ohne Modell“ mit Zahl", pg.inner_text("[data-ansicht='gcode']").startswith("▤ G-Code ohne Modell"))
            pg.click("[data-ansicht='gcode']")
            pg.wait_for_selector("#gcode-offen .af-zeile")
            zeile = pg.locator("#gcode-offen .af-zeile", has_text="unklar.gcode")
            check("Die Zeile nennt den Grund in Worten und beide Modelle gleichen Namens mit Ordner",
                  "2 Modelle heissen so" in zeile.inner_text() and zeile.locator("[data-gc-zu]").count() == 2 and "alt" in zeile.inner_text())
            check("Kachelraster ist weg, die eigene Fläche steht", pg.locator("#raster").is_hidden() and pg.locator("#gcode-offen").is_visible())
            if SCRATCH:
                pg.screenshot(path=os.path.join(SCRATCH, "gcode_offen.png"))
            zeile.locator("[data-gc-zu]").filter(has_text="alt").click()
            pg.wait_for_function("!document.querySelector('#gcode-offen').innerText.includes('unklar.gcode')")
            pg.wait_for_function("document.querySelector('#z-gcode')?.textContent === '1'")
            check("Klick auf ein Modell ordnet zu: Zeile weg, Zahl sinkt", True)
            pg.click("#gcode-offen [data-gc-waehlen]")
            pg.wait_for_selector("#gc-liste .w-zeile")
            check("„Modell wählen …“ sucht mit dem Kern des Dateinamens vor (ohne Zeitstempel und Platte)", pg.input_value("#gc-suche") == "Halter")
            pg.locator("#gc-liste .w-zeile", has_text="Halter_Umbenannt").locator("[data-gc-nimm]").click()
            pg.wait_for_function("document.querySelector('#z-gcode')?.textContent === ''")
            check("… und ein Klick ordnet zu; danach ist nichts mehr offen", "Alle G-Codes aus deinen Ordnern sind zugeordnet" in pg.inner_text("#gcode-offen"))
            b.close()
        ids = {m["name"]: m["id"] for m in abfrage(port, "/api/modelle")}
        h = abfrage(port, f"/api/modelle/{ids['Halter_Umbenannt']}")
        check("Am gewählten Modell hängt der G-Code als Druck „offen“", [d["ergebnis"] for d in h["drucke"]] == ["offen"])
    finally:
        server.terminate()
        server.wait(timeout=20)
    muster.ende()
