"""Backup als ZIP (KONZEPT §3.3a): was hinein kommt, Inhaltsverzeichnis, Zielordner, Aufbewahrung, nie ein halbes ZIP unter dem richtigen
Namen — und jede Art von Daten im Bestand gehört zu einer Zeile oder ist ausdrücklich ausgenommen."""
import io
import json
import os
import tempfile
import zipfile

import muster
from muster import check
from fastapi.testclient import TestClient
from PIL import Image
from partatlas import backup
from partatlas.main import erstelle_app

PDF = b"%PDF-1.4\n1 0 obj << >> endobj\ntrailer << >>\n%%EOF\n"
GCODE = b"; generated by PrusaSlicer 2.7.0\nG28\nG1 X10 Y10\n; filament used [g] = 3.2\n"


def fertig(c):
    z = c.app.state.zustand["backup"]
    z.warten(60)
    return z.status


def zip_von(ziel, name):
    return zipfile.ZipFile(os.path.join(ziel, name))


if __name__ == "__main__":
    muster.zeitgrenze(180)
    tmp = tempfile.mkdtemp()
    samm = os.path.join(tmp, "3D")
    os.makedirs(os.path.join(samm, "Halter"))
    muster.stl_binaer(os.path.join(samm, "Halter", "Halter.stl"), 10, 20, 30)
    muster.dreimf(os.path.join(samm, "Box.3mf"))
    with open(os.path.join(samm, "Notiz.txt"), "w") as f:
        f.write("kein Modell")
    ziel = os.path.join(tmp, "Backups")
    os.makedirs(ziel)

    with TestClient(erstelle_app(os.path.join(tmp, "bestand"), prozesse=2)) as c:
        z = c.app.state.zustand
        b = z["bestand"]
        c.post("/api/wurzeln", json={"pfad": samm})
        z["scanner"].warten(120)
        ids = {m["name"]: m["id"] for m in c.get("/api/modelle").json()}
        H = ids["Halter"]
        # Jede Art von Daten einmal anlegen: Anhang, eigenes Bild, Druck mit G-Code, entfernter Anhang (→ Aufgehobenes)
        c.post(f"/api/anhaenge/modell/{H}", params={"name": "Anleitung.pdf"}, content=PDF)
        k2 = c.post(f"/api/anhaenge/modell/{H}", params={"name": "alt.pdf"}, content=PDF + b"x").json()["k"]
        c.delete(f"/api/anhaenge/modell/{H}/{k2}")
        puffer = io.BytesIO()
        Image.new("RGB", (40, 30), (200, 80, 40)).save(puffer, "PNG")
        c.post(f"/api/modelle/{H}/bilder", content=puffer.getvalue(), headers={"Content-Type": "image/png"})
        did = c.post("/api/drucke", json={"modelle": [H]}).json().get("id")
        if did:
            c.post(f"/api/drucke/{did}/datei", params={"name": "Halter.gcode"}, content=GCODE)

        # -- Jede Art von Daten im Bestand gehört zu einer Zeile oder ist ausgenommen
        check(f"Jeder Ordner im Bestand gehört zu einer Backup-Zeile oder ist ausgenommen (unbekannt: {backup.unbekannt(b.wurzel)})",
              backup.unbekannt(b.wurzel) == [] and os.path.isdir(b.pfad("vault", "anhaenge")) and os.path.isdir(b.pfad("vault", "gcode")))
        os.makedirs(b.pfad("vault", "neuart"))
        with open(b.pfad("vault", "neuart", "x.bin"), "wb") as f:
            f.write(b"neu")
        check("Eine neue Art von Daten ohne Zeile wird gefunden", backup.unbekannt(b.wurzel) == ["vault/neuart"])

        # -- Übersicht: Zeilen mit Grösse, Vorgaben
        u = c.get("/api/backup").json()
        zeilen = {x["id"]: x for x in u["zeilen"]}
        check("Übersicht: Zeilen mit Anzahl und Grösse; Datenbank immer, Vorschaubilder aus, alles vom Anwender an",
              zeilen["katalog"]["immer"] and zeilen["katalog"]["an"] and not zeilen["vorschau"]["an"]
              and all(zeilen[x]["an"] for x in ("dateien", "bilder", "anhaenge", "gcode", "aufgehoben"))
              and zeilen["dateien"]["dateien"] == 2 and zeilen["dateien"]["bytes"] > 0 and zeilen["anhaenge"]["dateien"] == 1)
        check("Ohne Zielordner kein Backup, mit einem Satz dazu", c.post("/api/backup").status_code == 400)
        check("Zielordner im Bestand oder in einem Ordner mit Modellen abgelehnt",
              c.put("/api/backup", json={"ziel": b.pfad("arbeit")}).status_code == 400
              and c.put("/api/backup", json={"ziel": os.path.join(samm, "Halter")}).status_code == 400)
        check("Zielordner gesetzt", c.put("/api/backup", json={"ziel": ziel}).json()["ziel"] == ziel)

        # -- Erstellen
        c.post("/api/backup")
        st = fertig(c)
        name = st.get("letztes", {}).get("name", "")
        namen = zip_von(ziel, name).namelist() if name else []
        inhalt = json.loads(zip_von(ziel, name).read(backup.INHALT)) if name else {}
        check("Backup fertig: ein ZIP mit dem Namen des Tages, keine Arbeitsdatei", st.get("ergebnis") == "fertig"
              and backup.NAME.match(name) and not [n for n in os.listdir(ziel) if n.endswith(".arbeit")])
        check("Enthält Datenbank, Einstellungen, Modelldateien, Anhang, eigenes Bild, G-Code, Aufgehobenes",
              any(n.startswith("datenbank/") for n in namen) and "einstellungen.json" in namen
              and sum(n.startswith("dateien/") for n in namen) == 2 and any(n.endswith("Halter/Halter.stl") for n in namen)
              and any(n.startswith("vault/anhaenge/") for n in namen) and any(n.startswith("vault/bilder/") for n in namen)
              and (not did or any(n.startswith("vault/gcode/") for n in namen)) and any(n.startswith("vault_archive/") for n in namen))
        check("Nicht enthalten: Vorschaubilder (Vorgabe aus), Arbeitsdateien, Sicherungen, andere Dateien im Ordner",
              not any(n.startswith(("vault/vorschau/", "arbeit/", "sicherungen/")) for n in namen) and not any("Notiz.txt" in n for n in namen))
        check("Unbekanntes im Bestand kommt trotzdem mit (Zeile „sonstiges“)",
              "vault/neuart/x.bin" in namen and inhalt["zeilen"]["sonstiges"]["dateien"] == 1)
        check("Inhaltsverzeichnis: Fassung, Zeilen mit Anzahl, ausgelassene Zeilen, Wurzelordner, Modelle",
              inhalt["format"] == 1 and inhalt["partatlas"] and inhalt["zeilen"]["dateien"]["dateien"] == 2
              and inhalt["ausgelassen"] == ["vorschau"] and inhalt["wurzeln"][0]["pfad"] == samm and inhalt["modelle"] == 2)
        datei_im_zip = next(n for n in namen if n.endswith("Halter/Halter.stl"))
        check("Modelldatei unverändert im ZIP", zip_von(ziel, name).read(datei_im_zip) == open(os.path.join(samm, "Halter", "Halter.stl"), "rb").read())
        check("Letztes Backup gemerkt (für „Letztes Backup vor …“)", c.get("/api/backup").json()["letztes"]["name"] == name)

        # -- Zeile ausschalten, Aufbewahrung
        c.put("/api/backup", json={"zeilen": {"dateien": False, "vorschau": True, "katalog": False}})
        zeilen = {x["id"]: x for x in c.get("/api/backup").json()["zeilen"]}
        check("Zeilen umschalten; die Datenbank lässt sich nicht abwählen", not zeilen["dateien"]["an"] and zeilen["vorschau"]["an"] and zeilen["katalog"]["an"])
        for _ in range(2):
            c.post("/api/backup")
            st = fertig(c)
        namen = zip_von(ziel, st["letztes"]["name"]).namelist()
        check("Ohne Modelldateien, mit Vorschaubildern", not any(n.startswith("dateien/") for n in namen)
              and any(n.startswith("vault/vorschau/") for n in namen) and any(n.startswith("datenbank/") for n in namen))
        check("Behalten: die letzten 2 im Zielordner, das neueste ist dabei", len(backup.vorhandene(ziel)) == 2
              and backup.vorhandene(ziel)[0]["name"] == st["letztes"]["name"] and st["weggeraeumt"] == [name])
        fremd = os.path.join(ziel, "partAtlas-Backup-alt.zip")
        with open(fremd, "wb") as f:
            f.write(b"nicht unseres")
        c.post("/api/backup")
        fertig(c)
        check("Aufräumen nimmt nur Dateien mit unserem Namen", os.path.exists(fremd) and len(backup.vorhandene(ziel)) == 2)

        # -- Abbrechen: keine Arbeitsdatei, kein ZIP
        vorher = set(os.listdir(ziel))
        g = z["backup"]
        plan_vorher = g._plan

        def langsam(e):              # ein Plan mit vielen Dateien, damit der Abbruch mitten hinein trifft
            p = plan_vorher(e)
            return p + [("dateien", [(os.path.join(samm, "Halter", "Halter.stl"), f"dateien/x/{i}.stl", 1) for i in range(20000)])]
        g._plan = langsam
        c.post("/api/backup")
        g.abbrechen()
        st = fertig(c)
        g._plan = plan_vorher
        check("Abgebrochen: kein neues ZIP, keine Arbeitsdatei", st["ergebnis"] == "abgebrochen" and set(os.listdir(ziel)) == vorher)

        # -- Datei verschwindet: das Backup läuft durch und vermerkt sie
        c.put("/api/backup", json={"zeilen": {"dateien": True}})
        os.remove(os.path.join(samm, "Box.3mf"))
        c.post("/api/backup")
        st = fertig(c)
        inhalt = json.loads(zip_von(ziel, st["letztes"]["name"]).read(backup.INHALT))
        check("Fehlende Datei: Backup fertig, im Inhaltsverzeichnis als nicht lesbar vermerkt", st["ergebnis"] == "fertig"
              and inhalt["nicht_lesbar_n"] == 1 and inhalt["nicht_lesbar"][0].endswith("Box.3mf") and st["letztes"]["nicht_lesbar"] == 1)
    muster.ende()
